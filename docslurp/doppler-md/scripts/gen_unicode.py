"""Regenerate src/unicode_tables.rs: the character classes of the Python that produced the
reference output (str.isalnum/isdecimal/isspace/islower and re's \\w, \\d, \\s), as code point
ranges, so the port follows Python's Unicode version rather than Rust's."""
import pathlib
import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(sys.maxunicode + 1):
        ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1)); start = None
    if start is not None:
        out.append((start, sys.maxunicode))
    return out


TABLES = {
    'WORD': lambda c: c.isalnum() or c == '_',  # re \w for str patterns
    'DECIMAL': lambda c: c.isdecimal(),           # re \d
    'SPACE': lambda c: c.isspace(),               # re \s, str.strip/split
    'LOWER': lambda c: c.islower(),               # str.islower on one character
}

lines = ['// Generated by scripts/gen_unicode.py from Python %s (Unicode %s). Do not edit.'
         % (sys.version.split()[0], unicodedata.unidata_version)]
for name, pred in TABLES.items():
    rs = ranges(pred)
    lines.append(f'pub static {name}: &[(u32, u32)] = &[')
    for i in range(0, len(rs), 8):
        lines.append('    ' + ' '.join(f'(0x{a:x}, 0x{b:x}),' for a, b in rs[i:i + 8]))
    lines.append('];')
pathlib.Path(__file__).resolve().parent.parent.joinpath('src', 'unicode_tables.rs').write_text('\n'.join(lines) + '\n')
