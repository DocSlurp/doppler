"""Regenerate src/unicode_tables.rs: the character classes of the Python that produced the
reference output (str.isalnum/isdecimal/isspace/islower and re's \\w, \\d, \\s), as code point
ranges, plus str.lower()'s full lowercase mappings and the Cased / Case_Ignorable sets its final
sigma rule reads, so the port follows Python's Unicode version rather than Rust's."""
import pathlib
import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(sys.maxunicode + 1):
        ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1)); start = None
    if start is not None:
        out.append((start, sys.maxunicode))
    return out


TABLES = {
    'WORD': lambda c: c.isalnum() or c == '_',  # re \w for str patterns
    'DECIMAL': lambda c: c.isdecimal(),           # re \d
    'SPACE': lambda c: c.isspace(),               # re \s, str.strip/split
    'LOWER': lambda c: c.islower(),               # str.islower on one character
}



def surrogate(cp):
    return 0xd800 <= cp <= 0xdfff


# CPython's final sigma test reads Case_Ignorable and Cased, which Python does not expose; both
# follow from str.lower() itself. c + 'Σ' ends in 'ς' iff c is cased and not case-ignorable
# (an ignorable c is skipped and nothing cased precedes it); 'A' + c + 'Σ' ends in 'ς' iff c is
# cased or case-ignorable. Only these two sets matter: an ignorable character is always skipped.
def cased_stop(c):
    return not surrogate(ord(c)) and (c + '\u03a3').lower()[-1] == '\u03c2'


def ignorable(c):
    return not surrogate(ord(c)) and ('A' + c + '\u03a3').lower()[-1] == '\u03c2' and not cased_stop(c)


TABLES['CASED'] = cased_stop       # Cased and not Case_Ignorable
TABLES['CASE_IGNORABLE'] = ignorable

lines = ['// Generated by scripts/gen_unicode.py from Python %s (Unicode %s). Do not edit.'
         % (sys.version.split()[0], unicodedata.unidata_version)]
for name, pred in TABLES.items():
    rs = ranges(pred)
    lines.append(f'pub static {name}: &[(u32, u32)] = &[')
    for i in range(0, len(rs), 8):
        lines.append('    ' + ' '.join(f'(0x{a:x}, 0x{b:x}),' for a, b in rs[i:i + 8]))
    lines.append('];')
# str.lower() of every character but U+03A3 (context dependent), where it changes
lower = [(cp, chr(cp).lower()) for cp in range(sys.maxunicode + 1)
         if not surrogate(cp) and cp != 0x3a3 and chr(cp).lower() != chr(cp)]
lines.append('pub static LOWER_MAP: &[(u32, &str)] = &[')
for i in range(0, len(lower), 6):
    lines.append('    ' + ' '.join('(0x%x, "%s"),' % (cp, ''.join('\\u{%x}' % ord(ch) for ch in low))
                                   for cp, low in lower[i:i + 6]))
lines.append('];')
pathlib.Path(__file__).resolve().parent.parent.joinpath('src', 'unicode_tables.rs').write_text('\n'.join(lines) + '\n')
