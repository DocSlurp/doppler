#!/usr/bin/env python3
"""Generate poppler/CJKRadicals.h from Unicode's EquivalentUnifiedIdeograph.txt.

  python3 test/docslurp/unicode-mapping/gen_cjk_radicals.py EquivalentUnifiedIdeograph.txt > poppler/CJKRadicals.h

Only the CJK Radicals Supplement and Kangxi Radicals blocks (U+2E80..U+2FDF) are kept.
"""
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()
version = re.search(r"EquivalentUnifiedIdeograph-([\d.]+)\.txt", src).group(1)
pairs = []
for line in src.splitlines():
    m = re.match(r"^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*([0-9A-F]{4,6})", line)
    if not m:
        continue
    lo, hi, to = int(m.group(1), 16), int(m.group(2) or m.group(1), 16), int(m.group(3), 16)
    for cp in range(lo, hi + 1):
        if 0x2E80 <= cp <= 0x2FDF:
            pairs.append((cp, to))
pairs.sort()
print("// Generated by test/docslurp/unicode-mapping/gen_cjk_radicals.py from Unicode")
print("// EquivalentUnifiedIdeograph-%s.txt (Unicode License v3, https://www.unicode.org/license.txt)." % version)
print("// CJK Radicals Supplement and Kangxi Radicals mapped to their equivalent unified ideographs.")
print("#ifndef CJKRADICALS_H\n#define CJKRADICALS_H\n\n#include <array>\n#include <utility>\n")
print("static constexpr std::array<std::pair<unsigned int, unsigned int>, %d> cjkRadicalEquivalents { {" % len(pairs))
for i in range(0, len(pairs), 6):
    print("    " + ", ".join("{ 0x%04X, 0x%04X }" % p for p in pairs[i:i + 6]) + ",")
print("} };\n\n#endif")
